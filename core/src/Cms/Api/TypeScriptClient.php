<?php

declare(strict_types=1);

namespace Kestello\Cms\Api;

/**
 * Turns the OpenAPI document into one dependency-free TypeScript file: the
 * request and answer types of every operation, and createClient() with a
 * method per operation (named after its operationId).
 *
 *   const kestello = createClient({ baseUrl: 'https://example.com/api/v1', token: process.env.KESTELLO_TOKEN });
 *   const { data: posts } = await kestello.listEntries({ type: 'post', query: { status: 'published' } });
 *
 * Runs in browsers, Node.js 18+, Deno and Bun (anything with fetch).
 * bin/cms api:client writes it; GET /openapi.ts serves it for the caller.
 */
final class TypeScriptClient
{
    /** Bumped when the generated runtime changes in a way callers notice. */
    public const string VERSION = '1';

    private const array RESERVED = ['break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete', 'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if', 'import', 'in', 'instanceof', 'new', 'null', 'return', 'super', 'switch', 'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with'];

    /** @param array<string, mixed> $document an OpenApi::build() result */
    public static function generate(array $document, string $generatedAt = ''): string
    {
        $operations = self::operations($document);
        $site = (string) ($document['servers'][0]['url'] ?? '');

        $types = [];
        $methods = [];
        foreach ($operations as $op) {
            [$typeBlock, $method] = self::operation($op);
            $types[] = $typeBlock;
            $methods[] = $method;
        }

        $header = "/**\n * Kestello API client, generated by `php bin/cms api:client`" . ($site !== '' ? " from {$site}" : '') . ($generatedAt !== '' ? " on {$generatedAt}" : '') . ".\n"
            . " * Do not edit: generate it again after updating Kestello or its plugins.\n"
            . ' * ' . count($operations) . ' operations. Client format ' . self::VERSION . ".\n */\n";

        return $header . "\n" . self::RUNTIME_TYPES . "\n" . implode("\n", $types) . "\n" . self::runtime(implode("\n", $methods));
    }

    /**
     * The operations, sorted by name, with unique method names.
     *
     * @return list<array<string, mixed>>
     */
    private static function operations(array $document): array
    {
        $out = [];
        $seen = [];
        foreach ((array) ($document['paths'] ?? []) as $path => $methods) {
            foreach ((array) $methods as $method => $op) {
                $name = self::identifier((string) ($op['operationId'] ?? strtolower($method) . str_replace(['/', '{', '}', '-', '.'], ['_', '', '', '_', '_'], (string) $path)));
                if (isset($seen[$name])) {
                    // Two plugins with the same class name: tell them apart by owner.
                    $owner = (string) ($op['x-kestello-owner'] ?? 'core');
                    $name = self::identifier(lcfirst(str_replace(' ', '', ucwords(str_replace(['plugin:', 'theme:', '-', ':'], ['', '', ' ', ' '], $owner)))) . ucfirst($name));
                }
                $seen[$name] = true;
                $out[] = ['name' => $name, 'method' => strtoupper((string) $method), 'path' => (string) $path] + (array) $op;
            }
        }
        usort($out, static fn(array $a, array $b) => strcmp($a['name'], $b['name']));

        return $out;
    }

    /** @return array{0: string, 1: string} type declarations, client method */
    private static function operation(array $op): array
    {
        $Name = ucfirst($op['name']);
        $pathParams = array_values(array_filter((array) ($op['parameters'] ?? []), static fn(array $p) => ($p['in'] ?? '') === 'path'));
        $queryParams = array_values(array_filter((array) ($op['parameters'] ?? []), static fn(array $p) => ($p['in'] ?? '') === 'query'));
        $body = $op['requestBody']['content']['application/json']['schema'] ?? null;
        $ok = $op['responses']['200'] ?? $op['responses']['201'] ?? [];     // 201: it made something
        $data = $ok['content']['application/json']['schema']['properties']['data'] ?? [];

        $types = [];
        $types[] = "export type {$Name}Data = " . self::type((array) $data, 0) . ';';
        if ($queryParams !== []) {
            $props = [];
            foreach ($queryParams as $p) {
                $props[] = self::doc((array) ($p['schema'] ?? []), 1) . '    ' . self::key((string) $p['name']) . (($p['required'] ?? false) && !array_key_exists('default', (array) ($p['schema'] ?? [])) ? '' : '?') . ': ' . self::type((array) ($p['schema'] ?? []), 1) . ';';
            }
            $types[] = "export interface {$Name}Query {\n" . implode("\n", $props) . "\n}";
        }
        if ($body !== null) {
            $types[] = "export type {$Name}Body = " . self::type((array) $body, 0) . ';';
        }

        // The argument: path parameters at the top level, then query and body.
        $args = [];
        foreach ($pathParams as $p) {
            $args[] = self::key((string) $p['name']) . ': ' . ((($p['schema']['type'] ?? '') === 'integer') ? 'number | string' : 'string');
        }
        $queryRequired = array_filter($queryParams, static fn(array $p) => ($p['required'] ?? false) && !array_key_exists('default', (array) ($p['schema'] ?? []))) !== [];
        if ($queryParams !== []) {
            $args[] = 'query' . ($queryRequired ? '' : '?') . ": {$Name}Query";
        }
        if ($body !== null) {
            $args[] = "body: {$Name}Body";
        }
        $required = $pathParams !== [] || $body !== null || $queryRequired;
        $argType = $args === [] ? null : '{ ' . implode('; ', $args) . ' }';

        $path = preg_replace_callback('/\{([A-Za-z0-9_]+)\}/', static fn(array $m) => '${enc(args.' . $m[1] . ')}', $op['path']);
        // 204: nothing comes back. Documented for any method; a removal may always answer it
        $nothing = isset($op['responses']['204']) || $op['method'] === 'DELETE';
        $answer = $ok === [] && $nothing ? 'undefined' : "Answer<{$Name}Data>" . ($nothing ? ' | undefined' : '');

        $lines = [];
        $summary = trim((string) ($op['summary'] ?? ''));
        $lines[] = '        /**';
        if ($summary !== '') {
            $lines[] = '         * ' . self::comment($summary) . '.';
        }
        $lines[] = "         * `{$op['method']} {$op['path']}`";
        if (isset($op['x-kestello-capability'])) {
            $scopes = $op['security'][1]['bearer'] ?? [];
            $lines[] = '         * Needs the `' . $op['x-kestello-capability'] . '` capability' . ($scopes !== [] ? '; tokens need the scope ' . implode(', ', array_map(static fn($s) => "`{$s}`", $scopes)) : '') . '.';
        }
        if (!empty($op['x-kestello-recent-auth'])) {
            $lines[] = '         * In a browser session, needs a recent password entry.';
        }
        if (isset($op['x-kestello-owner'])) {
            $lines[] = '         * From ' . $op['x-kestello-owner'] . '.';
        }
        $file = array_values(array_diff(array_keys((array) ($ok['content'] ?? [])), ['application/json']))[0] ?? null;
        if ($file !== null) {
            $lines[] = '         * Answers a file (' . self::comment((string) $file) . '), not JSON: link to its address to download it.';
        }
        $lines[] = '         */';
        $param = $argType === null ? '' : 'args' . ($required ? '' : '?') . ': ' . $argType;
        $call = "request<{$answer}>('{$op['method']}', `{$path}`" . ($queryParams !== [] ? ', args?.query' : ', undefined') . ($body !== null ? ', args.body' : '') . ')';
        $call = str_replace('args.', $argType === null || $required ? 'args.' : 'args!.', $call);
        $lines[] = "        {$op['name']}: ({$param}): Promise<{$answer}> => {$call},";

        return [implode("\n", $types) . "\n", implode("\n", $lines)];
    }

    /** A JSON schema (OpenAPI 3.0 flavour) as a TypeScript type. */
    private static function type(array $schema, int $depth): string
    {
        if (isset($schema['$ref'])) {
            return basename((string) $schema['$ref']);
        }
        $nullable = !empty($schema['nullable']);
        $type = $schema['type'] ?? null;

        if (is_array($type)) {
            $ts = implode(' | ', array_unique(array_map(static fn($t) => self::type(['type' => $t], $depth), $type)));
        } elseif (isset($schema['enum'])) {
            $ts = implode(' | ', array_map(static fn($v) => json_encode($v, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE), (array) $schema['enum']));
        } else {
            $ts = match ($type) {
                'string' => 'string',
                'integer', 'number' => 'number',
                'boolean' => 'boolean',
                'null' => 'null',
                'array' => self::wrapArray(self::type((array) ($schema['items'] ?? []), $depth)),
                'object' => self::object($schema, $depth),
                default => 'unknown',
            };
        }

        return $nullable && $ts !== 'unknown' ? "{$ts} | null" : $ts;
    }

    private static function object(array $schema, int $depth): string
    {
        $props = (array) ($schema['properties'] ?? []);
        $additional = $schema['additionalProperties'] ?? null;
        if ($props === []) {
            return is_array($additional) ? 'Record<string, ' . self::type($additional, $depth) . '>' : 'Record<string, unknown>';
        }
        $required = (array) ($schema['required'] ?? []);
        $pad = str_repeat('    ', $depth + 1);
        $lines = [];
        foreach ($props as $name => $prop) {
            $lines[] = self::doc((array) $prop, $depth + 1) . $pad . self::key((string) $name) . (in_array($name, $required, true) ? '' : '?') . ': ' . self::type((array) $prop, $depth + 1) . ';';
        }
        if (is_array($additional)) {
            $lines[] = $pad . '[key: string]: unknown;';
        }

        return "{\n" . implode("\n", $lines) . "\n" . str_repeat('    ', $depth) . '}';
    }

    private static function wrapArray(string $item): string
    {
        return preg_match('/^[A-Za-z0-9_<>]+$/', $item) === 1 ? "{$item}[]" : "Array<{$item}>";
    }

    private static function doc(array $schema, int $depth): string
    {
        $text = trim((string) ($schema['description'] ?? ''));

        return $text === '' ? '' : str_repeat('    ', $depth) . '/** ' . self::comment($text) . " */\n";
    }

    private static function comment(string $text): string
    {
        return str_replace(['*/', "\n"], ['* /', ' '], $text);
    }

    private static function key(string $name): string
    {
        return preg_match('/^[A-Za-z_$][A-Za-z0-9_$]*$/', $name) === 1 ? $name : json_encode($name, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    }

    private static function identifier(string $name): string
    {
        $name = (string) preg_replace('/[^A-Za-z0-9_$]/', '_', $name);
        if ($name === '' || ctype_digit($name[0]) || in_array($name, self::RESERVED, true)) {
            $name = '_' . $name;
        }

        return $name;
    }

    private const string RUNTIME_TYPES = <<<'TS'
/** An error answer (application/problem+json). */
export interface Problem {
    type: string;
    title: string;
    status: number;
    detail?: string;
    /** Messages per field, for 422 answers: {"title": ["Give it a title."]} */
    errors?: Record<string, string[]>;
    [key: string]: unknown;
}

/** A successful answer: the data, and for lists, paging details in meta. */
export interface Answer<T> {
    data: T;
    meta?: Record<string, unknown>;
}

export interface ClientOptions {
    /** The API's address, such as "https://example.com/api/v1". */
    baseUrl: string;
    /** A personal access token (kst_pat_…). Leave it out in the admin, where the session cookie is used. */
    token?: string | (() => string | undefined | Promise<string | undefined>);
    /** For browser sessions: the CSRF token, sent with every request that changes something. */
    csrfToken?: string | (() => string | undefined);
    /** Extra headers for every request. */
    headers?: Record<string, string>;
    /** Defaults to the global fetch. */
    fetch?: typeof fetch;
    /** Defaults to "same-origin". */
    credentials?: RequestCredentials;
}

/** Thrown for every answer that is not a success. */
export class KestelloApiError extends Error {
    readonly status: number;
    readonly problem: Problem;
    /** Seconds to wait, for 429 answers. */
    readonly retryAfter: number | null;

    constructor(problem: Problem, retryAfter: number | null = null) {
        super(problem.detail || problem.title || `HTTP ${problem.status}`);
        this.name = 'KestelloApiError';
        this.status = problem.status;
        this.problem = problem;
        this.retryAfter = retryAfter;
    }

    /** The first message per field, for showing next to form fields. */
    fieldErrors(): Record<string, string> {
        const out: Record<string, string> = {};
        for (const [field, messages] of Object.entries(this.problem.errors ?? {})) {
            if (messages.length) out[field] = messages[0];
        }
        return out;
    }
}

TS;

    private static function runtime(string $methods): string
    {
        return <<<TS
type Query = object | undefined;

function enc(value: unknown): string {
    return encodeURIComponent(String(value));
}

function appendQuery(params: URLSearchParams, key: string, value: unknown): void {
    if (value === undefined || value === null) return;
    if (Array.isArray(value)) {
        for (const item of value) appendQuery(params, `\${key}[]`, item);
    } else if (typeof value === 'object') {
        for (const [k, v] of Object.entries(value as Record<string, unknown>)) appendQuery(params, `\${key}[\${k}]`, v);
    } else {
        params.append(key, String(value));
    }
}

/** A client for the Kestello REST API. Every method answers with { data, meta } or throws KestelloApiError. */
export function createClient(options: ClientOptions) {
    const base = options.baseUrl.replace(/\/+\$/, '');
    const doFetch = options.fetch ?? ((...a: Parameters<typeof fetch>) => fetch(...a));

    async function request<T>(method: string, path: string, query?: Query, body?: unknown): Promise<T> {
        const params = new URLSearchParams();
        for (const [k, v] of Object.entries(query ?? {})) appendQuery(params, k, v);
        const qs = params.toString();
        const headers: Record<string, string> = { Accept: 'application/json', ...(options.headers ?? {}) };
        const token = typeof options.token === 'function' ? await options.token() : options.token;
        if (token) headers.Authorization = `Bearer \${token}`;
        if (method !== 'GET') {
            const csrf = typeof options.csrfToken === 'function' ? options.csrfToken() : options.csrfToken;
            if (csrf) headers['X-CSRF-TOKEN'] = csrf;
        }
        if (body !== undefined) headers['Content-Type'] = 'application/json';

        const response = await doFetch(`\${base}\${path}\${qs ? `?\${qs}` : ''}`, {
            method,
            headers,
            body: body === undefined ? undefined : JSON.stringify(body),
            credentials: options.credentials ?? 'same-origin',
        });
        if (response.status === 204) return undefined as T;
        const text = await response.text();
        let parsed: unknown = undefined;
        try { parsed = text ? JSON.parse(text) : undefined; } catch { parsed = undefined; }
        if (!response.ok) {
            const problem = (parsed && typeof parsed === 'object' ? parsed : { type: 'about:blank', title: response.statusText || 'Request failed', status: response.status }) as Problem;
            if (typeof problem.status !== 'number') problem.status = response.status;
            const retry = response.headers.get('Retry-After');
            throw new KestelloApiError(problem, retry && /^\d+\$/.test(retry) ? Number(retry) : null);
        }
        return parsed as T;
    }

    return {
        /** Any endpoint, including ones added after this file was generated. */
        request,
{$methods}
    };
}

export type KestelloClient = ReturnType<typeof createClient>;

TS;
    }
}
