<?php

declare(strict_types=1);

namespace Kestello\Framework\Database\Grammar;

use Kestello\Framework\Database\ColumnDefinition;

final class PostgresSchemaGrammar extends SchemaGrammar
{
    protected function type(ColumnDefinition $c): string
    {
        $type = match ($c->type) {
            'string' => "VARCHAR({$c->options['length']})",
            'char' => "CHAR({$c->options['length']})",
            'text', 'mediumText', 'longText' => 'TEXT',
            'tinyInteger', 'smallInteger' => 'SMALLINT',
            'integer' => 'INTEGER',
            'bigInteger' => 'BIGINT',
            'boolean' => 'BOOLEAN',
            'decimal' => "NUMERIC({$c->options['precision']},{$c->options['scale']})",
            'double' => 'DOUBLE PRECISION',
            'date' => 'DATE',
            'time' => 'TIME(0) WITHOUT TIME ZONE',
            'datetime' => 'TIMESTAMP(0) WITHOUT TIME ZONE',
            'json' => 'JSONB',
            'uuid' => 'UUID',
            'binary' => 'BYTEA',
            'enum' => 'VARCHAR(255)',
        };

        return $c->autoIncrement ? $type . ' GENERATED BY DEFAULT AS IDENTITY' : $type;
    }

    protected function literal(mixed $value, ?ColumnDefinition $column = null): string
    {
        if ($column?->type === 'boolean' && $value !== null) {
            return filter_var($value, FILTER_VALIDATE_BOOL) ? 'TRUE' : 'FALSE';
        }

        return parent::literal($value, $column);
    }

    public function compileCreate(\Kestello\Framework\Database\Blueprint $blueprint, array $options = []): array
    {
        $statements = parent::compileCreate($blueprint, $options);

        foreach ($blueprint->columns() as $column) {
            if ($column->comment !== null) {
                $statements[] = 'COMMENT ON COLUMN ' . $this->wrap($blueprint->table) . '.' . $this->wrap($column->name) . ' IS ' . $this->literal($column->comment);
            }
        }

        return $statements;
    }

    public function compileHasTable(string $table): array
    {
        return ['SELECT COUNT(*) AS n FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ?', [$table]];
    }

    public function compileColumns(string $table): array
    {
        return ['SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position', [$table]];
    }

    public function compileIndexes(string $table): array
    {
        return ['SELECT indexname AS name FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ? ORDER BY indexname', [$table]];
    }

    public function compileAllColumns(): array
    {
        return ['SELECT table_name AS tbl, column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() ORDER BY table_name, ordinal_position', []];
    }

    public function compileAllIndexes(): array
    {
        return ['SELECT tablename AS tbl, indexname AS name FROM pg_indexes WHERE schemaname = current_schema() ORDER BY tablename, indexname', []];
    }

    public function compileTables(): array
    {
        return ["SELECT table_name AS name FROM information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' ORDER BY table_name", []];
    }
}
